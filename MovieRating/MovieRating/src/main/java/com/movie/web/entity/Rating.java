/**
 * 评分实体类 - 用户电影评分数据的Java对象表示
 * 
 * 这个类是电影评分系统的核心数据模型，代表了用户对电影的评分记录。
 * 它承担着以下重要职责：
 * 
 * 1. 评分数据载体：封装用户评分的完整信息
 * 2. HBase数据映射：与HBase中的ratings表结构对应
 * 3. 业务逻辑支持：为推荐算法提供基础数据
 * 4. API数据传输：支持前后端的评分数据交换
 * 
 * 设计特点：
 * - 使用复合RowKey设计，支持多维度查询
 * - 包含时间戳，支持时序分析
 * - 字段类型统一为String，与HBase存储保持一致
 * - 支持用户维度和电影维度的双向查询
 * 
 * 数据来源：
 * - MovieLens数据集中的ratings.csv文件
 * - 用户通过Web界面提交的实时评分
 * - 移动应用或第三方系统的评分数据
 * 
 * 使用场景：
 * - 用户评分历史查询
 * - 电影评分统计分析
 * - 推荐算法的训练数据
 * - 用户行为分析和挖掘
 * 
 * HBase存储策略：
 * - RowKey设计：userId_movieId_timestamp，支持高效查询
 * - 列族设计：info列族存储评分详情
 * - 索引策略：支持按用户ID和电影ID的快速检索
 */
@Data  // 自动生成getter、setter、toString、equals、hashCode方法
       // 这大大减少了样板代码，让类更加简洁
@NoArgsConstructor   // 生成无参构造函数，用于：
                     // 1. Spring框架的Bean实例化
                     // 2. JSON反序列化
                     // 3. HBase数据反序列化
@AllArgsConstructor  // 生成包含所有字段的构造函数，用于：
                     // 1. 快速创建完整的Rating对象
                     // 2. 数据转换和映射
                     // 3. 测试数据的构造
public class Rating {
  
  /**
   * 行键 - HBase中的唯一标识符
   * 
   * 这是Rating在HBase中的主键，采用复合键设计：
   * 格式：userId_movieId_timestamp
   * 
   * 设计优势：
   * - 唯一性保证：确保每条评分记录的唯一性
   * - 查询效率：支持按用户ID前缀查询用户所有评分
   * - 数据分布：通过用户ID实现数据的均匀分布
   * - 时序支持：包含时间戳，支持时间维度的分析
   * 
   * 查询模式：
   * - 精确查询：根据完整RowKey查询特定评分
   * - 前缀查询：根据userId前缀查询用户所有评分
   * - 范围查询：根据userId范围查询多个用户的评分
   * 
   * 使用场景：
   * - HBase数据的唯一标识
   * - 评分记录的精确定位
   * - 数据去重和更新操作
   * - 分布式存储的数据分片
   * 
   * 注意事项：
   * - RowKey设计影响HBase的查询性能
   * - 需要避免热点问题（数据倾斜）
   * - 长度要适中，过长影响存储效率
   */
  private String rowKey;
  
  /**
   * 用户ID - 评分用户的唯一标识
   * 
   * 这个字段标识了给出评分的用户，具有以下特点：
   * - 用户唯一性：每个用户都有唯一的ID
   * - 关联查询：用于查询用户的所有评分记录
   * - 推荐基础：推荐算法中的用户维度
   * - 隐私保护：使用ID而非真实用户信息
   * 
   * 数据特征：
   * - 数据类型：字符串格式的数字ID
   * - 数据范围：通常为正整数
   * - 数据来源：用户注册时分配或外部系统导入
   * 
   * 使用场景：
   * - 查询用户的评分历史
   * - 用户行为分析和画像
   * - 协同过滤推荐算法
   * - 用户活跃度统计
   * 
   * 查询优化：
   * - 作为RowKey的一部分，支持高效的前缀查询
   * - 可以建立二级索引提高查询性能
   * - 支持用户维度的数据聚合
   * 
   * 注意事项：
   * - 需要与用户系统保持一致性
   * - 考虑用户隐私和数据安全
   * - 处理用户注销后的数据清理
   */
  private String userId;
  
  /**
   * 电影ID - 被评分电影的唯一标识
   * 
   * 这个字段标识了被评分的电影，与Movie实体的movieId对应：
   * - 电影关联：与电影基本信息建立关联关系
   * - 统计分析：用于计算电影的平均评分和评分分布
   * - 推荐算法：基于物品的协同过滤推荐
   * - 数据一致性：确保评分数据的完整性
   * 
   * 数据特征：
   * - 数据类型：字符串格式的数字ID
   * - 数据来源：MovieLens数据集或电影数据库
   * - 外键关系：引用movies表中的电影记录
   * 
   * 使用场景：
   * - 查询电影的所有评分记录
   * - 计算电影的评分统计信息
   * - 基于物品的推荐算法
   * - 电影热度和受欢迎程度分析
   * 
   * 查询模式：
   * - 通过Scan操作查询电影的所有评分
   * - 结合过滤器进行条件查询
   * - 支持电影维度的数据聚合
   * 
   * 注意事项：
   * - 需要确保电影ID的有效性
   * - 处理电影下架后的评分数据
   * - 考虑电影合并或拆分的情况
   */
  private String movieId;
  
  /**
   * 评分值 - 用户给出的具体评分
   * 
   * 这是评分记录的核心数据，代表用户对电影的喜好程度：
   * - 评分范围：通常为0.5-5.0，步长0.5
   * - 数据精度：支持半星评分，提供更细粒度的评价
   * - 业务含义：数值越高表示用户越喜欢该电影
   * - 算法基础：推荐算法的核心输入数据
   * 
   * 评分标准：
   * - 5.0：非常喜欢，强烈推荐
   * - 4.0-4.5：比较喜欢，值得观看
   * - 3.0-3.5：一般般，可看可不看
   * - 2.0-2.5：不太喜欢，不推荐
   * - 1.0-1.5：非常不喜欢，强烈不推荐
   * - 0.5：最低评分
   * 
   * 数据处理：
   * - 存储为字符串，便于HBase存储和传输
   * - 计算时需要转换为数值类型
   * - 支持评分的统计分析和聚合计算
   * 
   * 使用场景：
   * - 电影评分统计（平均分、分布等）
   * - 用户偏好分析
   * - 推荐算法的相似度计算
   * - 电影质量评估和排序
   * 
   * 注意事项：
   * - 需要验证评分值的有效性
   * - 处理异常评分和恶意评分
   * - 考虑评分的时效性和权重
   */
  private String rating;
  
  /**
   * 时间戳 - 评分产生的时间
   * 
   * 这个字段记录了用户给出评分的具体时间，具有重要的分析价值：
   * - 时序分析：支持基于时间的数据分析
   * - 数据新鲜度：判断评分数据的时效性
   * - 用户行为：分析用户的评分习惯和活跃时段
   * - 趋势分析：观察电影评分随时间的变化趋势
   * 
   * 时间格式：
   * - 通常为Unix时间戳格式
   * - 精确到秒级，满足大部分分析需求
   * - 存储为字符串，便于HBase处理
   * 
   * 数据用途：
   * - 评分时序分析：观察评分随时间的分布
   * - 用户活跃度：分析用户的评分频率和时间模式
   * - 电影生命周期：分析电影上映后的评分变化
   * - 数据清理：识别和处理过期或异常的评分数据
   * 
   * 使用场景：
   * - 时间维度的数据查询和过滤
   * - 评分趋势分析和可视化
   * - 用户行为模式挖掘
   * - 推荐算法中的时间衰减因子
   * 
   * 查询优化：
   * - 可以作为查询条件进行时间范围过滤
   * - 支持按时间排序的评分列表
   * - 便于实现数据的分区和归档
   * 
   * 注意事项：
   * - 时区处理和标准化
   * - 时间戳的精度和格式统一
   * - 考虑夏令时等特殊情况
   * - 数据迁移时的时间戳转换
   */
  private String timestamp;
}
